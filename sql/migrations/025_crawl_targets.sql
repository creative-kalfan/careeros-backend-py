CREATE OR REPLACE FUNCTION public.claim_due_crawl_targets(p_limit INT, p_lease_seconds INT)
RETURNS SETOF public.crawl_targets
LANGUAGE sql SECURITY DEFINER SET search_path = public
AS $$
    WITH due AS (
        SELECT id FROM public.crawl_targets
        WHERE status = 'active' AND next_run_at <= now()
          AND (lease_until IS NULL OR lease_until <= now())
        ORDER BY priority ASC, next_run_at ASC
        FOR UPDATE SKIP LOCKED
        LIMIT GREATEST(1, p_limit)
    )
    UPDATE public.crawl_targets AS target
    SET lease_until = now() + make_interval(secs => GREATEST(1, p_lease_seconds)),
        last_attempt_at = now(), updated_at = now()
    FROM due WHERE target.id = due.id
    RETURNING target.*;
$$;
REVOKE ALL ON FUNCTION public.claim_due_crawl_targets(INT, INT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_due_crawl_targets(INT, INT) TO service_role;

CREATE OR REPLACE FUNCTION public.complete_crawl_target(
    p_source TEXT, p_slug TEXT, p_success BOOLEAN, p_interval_minutes INT,
    p_job_count INT DEFAULT 0, p_content_hash TEXT DEFAULT NULL,
    p_error TEXT DEFAULT NULL, p_not_found BOOLEAN DEFAULT FALSE,
    p_min_interval_minutes INT DEFAULT 360,
    p_max_interval_minutes INT DEFAULT 2880,
    p_dead_after_failures INT DEFAULT 10
) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
    row_target public.crawl_targets%ROWTYPE;
    next_interval INT;
    next_failures INT;
    unchanged INT;
    empty_streak INT;
BEGIN
    SELECT * INTO row_target FROM public.crawl_targets
    WHERE source = p_source AND slug = p_slug FOR UPDATE;
    IF NOT FOUND THEN RETURN; END IF;

    IF p_success THEN
        unchanged := CASE WHEN p_content_hash IS NOT NULL AND p_content_hash = row_target.content_hash
                          THEN row_target.hash_unchanged_streak + 1 ELSE 0 END;
        empty_streak := CASE WHEN COALESCE(p_job_count, 0) = 0
                             THEN row_target.zero_job_streak + 1 ELSE 0 END;
        next_interval := LEAST(p_max_interval_minutes, GREATEST(p_min_interval_minutes, p_interval_minutes));
        IF empty_streak >= 3 THEN next_interval := p_max_interval_minutes; END IF;
        IF row_target.priority = 0 THEN next_interval := LEAST(next_interval, 1440); END IF;
        UPDATE public.crawl_targets SET
            last_success_at = now(), consecutive_failures = 0, consecutive_not_found = 0,
            last_error = NULL, last_job_count = p_job_count,
            hash_unchanged_streak = unchanged,
            zero_job_streak = empty_streak,
            content_hash = COALESCE(p_content_hash, content_hash),
            interval_minutes = next_interval,
            next_run_at = now() + make_interval(mins => next_interval),
            lease_until = NULL, updated_at = now()
        WHERE id = row_target.id;
    ELSE
        next_failures := row_target.consecutive_failures + 1;
        UPDATE public.crawl_targets SET
            consecutive_failures = next_failures,
            consecutive_not_found = CASE WHEN p_not_found THEN consecutive_not_found + 1 ELSE 0 END,
            last_error = left(COALESCE(p_error, 'crawl failed'), 1000),
            status = CASE WHEN next_failures >= GREATEST(1, p_dead_after_failures)
                               OR (p_not_found AND row_target.consecutive_not_found + 1 >= 3)
                          THEN 'dead' ELSE status END,
            next_run_at = now() + make_interval(secs => LEAST(86400,
                GREATEST(60, p_interval_minutes * 60 * power(2, LEAST(next_failures, 10)))
                * (0.9 + random() * 0.2))),
            lease_until = NULL, updated_at = now()
        WHERE id = row_target.id;
    END IF;
END;
$$;
REVOKE ALL ON FUNCTION public.complete_crawl_target(TEXT, TEXT, BOOLEAN, INT, INT, TEXT, TEXT, BOOLEAN, INT, INT, INT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.complete_crawl_target(TEXT, TEXT, BOOLEAN, INT, INT, TEXT, TEXT, BOOLEAN, INT, INT, INT) TO service_role;

ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS missed_crawls SMALLINT NOT NULL DEFAULT 0;

CREATE OR REPLACE FUNCTION public.reset_job_missed_crawls()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    IF TG_OP = 'INSERT' OR NEW.last_seen_at IS DISTINCT FROM OLD.last_seen_at THEN
        NEW.missed_crawls := 0;
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS jobs_reset_missed_crawls ON public.jobs;
CREATE TRIGGER jobs_reset_missed_crawls
    BEFORE INSERT OR UPDATE ON public.jobs
    FOR EACH ROW EXECUTE FUNCTION public.reset_job_missed_crawls();

CREATE OR REPLACE FUNCTION public.deactivate_unseen_jobs_batch(
    p_source TEXT, p_company TEXT, p_careers_url TEXT, p_since TIMESTAMPTZ, p_threshold SMALLINT
) RETURNS INT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE changed INT;
BEGIN
    WITH marked AS (
        UPDATE public.jobs SET missed_crawls = missed_crawls + 1,
            is_active = CASE WHEN missed_crawls + 1 >= GREATEST(1, p_threshold) THEN FALSE ELSE is_active END
        WHERE is_active = TRUE AND source_platform = p_source
          AND (p_company IS NULL OR company = p_company)
          AND (p_careers_url IS NULL OR careers_url = p_careers_url)
          AND last_seen_at IS NOT NULL AND last_seen_at < p_since
        RETURNING is_active
    )
    SELECT count(*) FILTER (WHERE NOT is_active) INTO changed FROM marked;
    RETURN changed;
END;
$$;
REVOKE ALL ON FUNCTION public.deactivate_unseen_jobs_batch(TEXT, TEXT, TEXT, TIMESTAMPTZ, SMALLINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.deactivate_unseen_jobs_batch(TEXT, TEXT, TEXT, TIMESTAMPTZ, SMALLINT) TO service_role;
