-- Durable crawl schedule. Apply manually in the Supabase SQL Editor.
CREATE TABLE IF NOT EXISTS public.crawl_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    slug TEXT NOT NULL DEFAULT '',
    priority INT NOT NULL DEFAULT 1,
    interval_minutes INT NOT NULL DEFAULT 1440 CHECK (interval_minutes > 0),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('candidate', 'active', 'paused', 'dead')),
    next_run_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    lease_until TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    consecutive_failures INT NOT NULL DEFAULT 0,
    consecutive_not_found INT NOT NULL DEFAULT 0,
    last_error TEXT,
    last_job_count INT,
    content_hash TEXT,
    hash_unchanged_streak INT NOT NULL DEFAULT 0,
    zero_job_streak INT NOT NULL DEFAULT 0,
    last_discovery_probe_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source, slug)
);

CREATE INDEX IF NOT EXISTS crawl_targets_due_idx
    ON public.crawl_targets (status, next_run_at);
ALTER TABLE public.crawl_targets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.crawl_targets FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crawl_targets TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.crawl_targets_id_seq TO service_role;

